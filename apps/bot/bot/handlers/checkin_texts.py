# ---- PR №9: pre-filter сообщения ------------------------------------------
# Бот проверяет allowed_proof_types ДО отправки в backend, чтобы юзер
# сразу получил понятное сообщение вместо «Принято» (когда worker
# асинхронно отвергает задачу с code=wrong_type).


def reject_wrong_type_single(name: str, emoji: str, title: str) -> str:
    """Клуб принимает один тип. {name} отправил другой."""
    return (
        f"↩ {emoji} {name}, в этом клубе принимается только {title}.\n"
        f"Отправь {emoji} {title.lower()}."
    )


def reject_wrong_type_multi(name: str, allowed_lines: list[str]) -> str:
    """Клуб принимает несколько типов. Юзер отправил что-то вне списка."""
    allowed = "\n".join(f"  {line}" for line in allowed_lines)
    return (
        f"↩ 🎯 {name}, этот клуб принимает только:\n{allowed}\n\n"
        f"Отправь любой из этих типов."
    )


